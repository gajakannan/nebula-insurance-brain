STATUS_RQ = f"""PREFIX fnd: <{F}>
PREFIX d: <{D}>
# EX-PC-001/021 on foundation IRIs: every account with its organization and status at the snapshot coordinate.
SELECT ?account ?organization ?status WHERE {{
  ?account a fnd:account ; fnd:account.organization ?organization ; fnd:account.status ?status .
}} ORDER BY ?account
"""


def kebab(label: str) -> str:
    out = ""
    for i, ch in enumerate(label):
        out += ("-" if i and ch.isupper() else "") + ch.lower()
    return out


def convert(graph):  # type: ignore[no-untyped-def]
    from rdflib import RDF, RDFS, Graph, Literal, URIRef

    out = Graph()
    out.bind("fnd", F)
    out.bind("d", D)
    out.bind("rdfs", str(RDFS))
    role_kinds = {s for s in graph.subjects(RDF.type, URIRef(PC + "RoleKind"))}
    kind_iri = {s: URIRef(F + "role-kind." + kebab(str(graph.value(s, RDFS.label)))) for s in role_kinds}
    accounts = set(graph.subjects(RDF.type, URIRef(PC + "Account")))
    keep_assignments = {
        a for a in graph.subjects(RDF.type, URIRef(PC + "RoleAssignment"))
        if graph.value(a, URIRef(PC + "roleScope")) in accounts
    }
    for s, p, o in graph:
        if s in role_kinds:
            continue
        if (s, RDF.type, URIRef(PC + "RoleAssignment")) in graph and s not in keep_assignments:
            continue
        if p == RDF.type:
            name = str(o).removeprefix(PC)
            if name in CLASSES:
                out.add((s, RDF.type, URIRef(F + CLASSES[name])))
            continue
        if p == RDFS.label:
            if any((s, RDF.type, URIRef(PC + c)) in graph for c in CLASSES):
                out.add((s, p, o))
            continue
        name = str(p).removeprefix(PC)
        if name not in PROPERTIES:
            continue
        if name == "accountStatus":
            o = URIRef(F + STATUS[str(o)])
        elif name == "roleKind":
            o = kind_iri[o]
        elif name == "ownershipPercent":
            o = Literal(o.toPython(), datatype=o.datatype)
        out.add((s, URIRef(F + PROPERTIES[name]), o))
    return out


def canonical_jsonld(value):  # type: ignore[no-untyped-def]
    """Recursively sort JSON-LD arrays by their canonical JSON text."""
    if isinstance(value, dict):
        return {k: canonical_jsonld(v) for k, v in value.items()}
    if isinstance(value, list):
        items = [canonical_jsonld(v) for v in value]
        return sorted(items, key=lambda v: json.dumps(v, sort_keys=True))
    return value


def outputs() -> dict[str, str]:
    from rdflib import Graph

    files: dict[str, str] = {}
    snapshot = convert(Graph().parse(SOURCE / "snapshot.ttl", format="turtle"))
    files["snapshot.ttl"] = HEADER + snapshot.serialize(format="turtle")
    # rdflib's JSON-LD node and value order varies across versions; sort them so the
    # file is byte-stable (JSON-LD arrays here are unordered sets, no @list).
    files["snapshot.jsonld"] = json.dumps(
        canonical_jsonld(json.loads(snapshot.serialize(format="json-ld"))), indent=2, sort_keys=True
    ) + "\n"
    for name, _ in BOUNDARIES:
        graph = convert(Graph().parse(SOURCE / "boundaries" / name, format="turtle"))
        files[f"boundaries/{name}"] = HEADER + graph.serialize(format="turtle")
    files["boundaries/role-scope-not-member.ttl"] = NOT_MEMBER
    files["shapes.ttl"] = SHAPES
    files["queries/ownership.rq"] = OWNERSHIP_RQ
    files["queries/account-team.rq"] = TEAM_RQ
    files["queries/account-status.rq"] = STATUS_RQ
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for name, text in outputs().items():
        path = TARGET / name
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if stale:
        print(json.dumps({"status": "fail", "stale": stale}, indent=2))
        return 1
    print(json.dumps({"status": "pass" if args.check else "written", "folder": str(TARGET.relative_to(ROOT))}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
