#!/usr/bin/env python3
"""Re-express the account-scoped Cedar Bridge fixtures on production foundation IRIs (F0012-S0003 AC7).

Reads the illustrative `pc:` snapshot and account boundaries and writes
`planning-mds/examples/commercial-pc-account/foundation/` with `urn:nebula:ont:foundation.*`
terms. Policy, policy-term, submission and program statements are dropped; F0013 re-expresses
the policy-dependent cases (EX-PC-016/018/019/020). Run with the `semantic-rdf` tools:

    python scripts/validation/build_foundation_examples.py [--check]

`--check` compares the committed files instead of writing them.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "planning-mds/examples/commercial-pc-account"
TARGET = SOURCE / "foundation"
PC = "https://example.invalid/nebula/ont/commercial-example/"
D = "https://example.invalid/nebula/data/"
F = "urn:nebula:ont:foundation."

CLASSES = {
    "Account": "account",
    "Organization": "organization",
    "Person": "person",
    "Location": "place",
    "OwnershipInterest": "ownership-interest",
    "RoleAssignment": "role-assignment",
}
PROPERTIES = {
    "accountOrganization": "account.organization",
    "accountStatus": "account.status",
    "parentAccount": "account.parent-account",
    "owner": "ownership-interest.owner",
    "ownedOrganization": "ownership-interest.owned-organization",
    "ownershipPercent": "ownership-interest.percentage",
    "roleParty": "role-assignment.party",
    "roleKind": "role-assignment.role-kind",
    "roleScope": "role-assignment.scope",
    "actsFor": "role-assignment.acted-for",
    "employedBy": "person.employed-by",
    "operatesAt": "organization.operates-at",
    "parentOrganization": "organization.parent-organization",
}
STATUS = {"CURRENT": "account-status.current", "CLOSED": "account-status.closed"}
BOUNDARIES = (
    ("self-parent.ttl", False),
    ("parent-cycle.ttl", False),
    ("ownership-over-100.ttl", False),
    ("two-parent-accounts.ttl", False),
    ("duplicate-organization-account.ttl", False),
    ("account-close-reopen.ttl", True),
    ("jv-designated-parent.ttl", True),
)
HEADER = "# GENERATED by scripts/validation/build_foundation_examples.py from the illustrative pc: fixture. Do not edit.\n"

SHAPES = f"""{HEADER}@prefix fnd: <{F}> .
@prefix sh: <http://www.w3.org/ns/shacl#> .
@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .
@prefix ex: <https://example.invalid/nebula/shapes/foundation/> .

# Example-validation shapes for the foundation constraints (ADR-0070, ADR-0081 D2). The data graph is
# the snapshot plus the installed foundation release, so sh:class follows rdfs:subClassOf.
ex:AccountShape a sh:NodeShape ; sh:targetClass fnd:account ;
    sh:property [ sh:path fnd:account.organization ; sh:minCount 1 ; sh:maxCount 1 ; sh:class fnd:organization ] ;
    sh:property [ sh:path fnd:account.status ; sh:minCount 1 ; sh:maxCount 1 ;
        sh:in ( fnd:account-status.current fnd:account-status.closed ) ] ;
    # foundation.constraint.one-parent-account (stage example-validation).
    sh:property [ sh:path fnd:account.parent-account ; sh:maxCount 1 ; sh:class fnd:account ] ;
    sh:sparql [ sh:message "An account cannot be its own parent or ancestor." ;
        sh:select \"\"\"SELECT $this WHERE {{ $this <{F}account.parent-account>+ $this }}\"\"\" ] .

ex:OneCurrentAccountShape a sh:NodeShape ; sh:targetObjectsOf fnd:account.organization ;
    sh:sparql [ sh:message "An organization may have at most one current account in this tenant snapshot." ;
        sh:select \"\"\"SELECT DISTINCT $this WHERE {{
            ?account <{F}account.organization> $this ; <{F}account.status> <{F}account-status.current> .
            ?other <{F}account.organization> $this ; <{F}account.status> <{F}account-status.current> .
            FILTER (?account != ?other) }}\"\"\" ] .

ex:OwnershipShape a sh:NodeShape ; sh:targetClass fnd:ownership-interest ;
    sh:property [ sh:path fnd:ownership-interest.owner ; sh:minCount 1 ; sh:maxCount 1 ; sh:class fnd:party ] ;
    sh:property [ sh:path fnd:ownership-interest.owned-organization ; sh:minCount 1 ; sh:maxCount 1 ;
        sh:class fnd:organization ] ;
    sh:property [ sh:path fnd:ownership-interest.percentage ; sh:minCount 1 ; sh:maxCount 1 ;
        sh:datatype xsd:decimal ; sh:minExclusive 0 ; sh:maxInclusive 100 ] .

ex:OwnershipTotalShape a sh:NodeShape ; sh:targetObjectsOf fnd:ownership-interest.owned-organization ;
    sh:sparql [ sh:message "Recorded ownership percentages for one organization total more than 100." ;
        sh:select \"\"\"SELECT $this WHERE {{
            ?interest <{F}ownership-interest.owned-organization> $this ;
                <{F}ownership-interest.percentage> ?percent }}
            GROUP BY $this HAVING (SUM(?percent) > 100)\"\"\" ] .

# S0003 AC4: a role scope must be a member of the role-scope class (Account in foundation).
ex:RoleAssignmentShape a sh:NodeShape ; sh:targetClass fnd:role-assignment ;
    sh:property [ sh:path fnd:role-assignment.party ; sh:minCount 1 ; sh:maxCount 1 ; sh:class fnd:party ] ;
    sh:property [ sh:path fnd:role-assignment.role-kind ; sh:minCount 1 ; sh:maxCount 1 ; sh:class fnd:role-kind ] ;
    sh:property [ sh:path fnd:role-assignment.scope ; sh:minCount 1 ; sh:maxCount 1 ; sh:class fnd:role-scope ] .
"""

